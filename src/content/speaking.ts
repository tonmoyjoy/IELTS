import type { SpeakingSet } from "@/content/types";
import sets from "@/content/speaking-sets.json";
import examinerLines from "@/content/examiner-lines.json";

/**
 * Speaking content lives in JSON so that `scripts/generate-audio.mjs` can
 * render the examiner's voice for every question without a TypeScript build.
 */
export const speakingSets: SpeakingSet[] = sets;

export type ExaminerLineKey = keyof typeof examinerLines;
export const EXAMINER_LINES: Record<ExaminerLineKey, string> = examinerLines;

export function getSpeakingSet(id: string): SpeakingSet | undefined {
  return speakingSets.find((set) => set.id === id);
}

/** Text the examiner reads for the Part 2 cue card. */
export function cueCardScript(set: SpeakingSet): string {
  return `${set.part2.cue} You should say: ${set.part2.bullets.join(", ")}.`;
}

/** Public URL of a pre-rendered examiner clip (generated by `npm run audio:generate`). */
export function examinerAudioSrc(key: string, setId?: string): string {
  return setId ? `/speaking/${setId}/${key}.mp3` : `/speaking/common/${key}.mp3`;
}
